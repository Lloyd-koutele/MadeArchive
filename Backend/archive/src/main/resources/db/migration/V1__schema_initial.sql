-- Schéma de base (état d'avant V2) : permet de créer une installation NEUVE.
--
-- Jusqu'ici, aucune migration V1 n'existait : le schéma initial était créé par Hibernate
-- (ddl-auto=update) et Flyway le « baselinait » à la version 1 (spring.flyway.baseline-on-migrate).
-- Sur une base VIDE, V2 échouait donc (« relation journal_audit does not exist »).
--
-- Ce script reproduit le schéma tel que le produisait Hibernate au moment de l'introduction de Flyway
-- (extrait par pg_dump d'une base créée avec le code du commit précédant V2). Une base DÉJÀ existante
-- n'est pas affectée : Flyway la baseline à la version 1 sans exécuter ce fichier.

